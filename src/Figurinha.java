public class Figurinha {
    public int numero;
    public String nome;
    public String conteudo;
    public int nroPagina;
    public int status;

    public Figurinha(int numero, String nome, String conteudo, int nroPagina, int status) {
        this.numero = numero;
        this.nome = nome;
        this.conteudo = conteudo;
        this.nroPagina = nroPagina;
        this.status = status;
    }
}